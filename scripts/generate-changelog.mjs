import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const scriptPath = fileURLToPath(import.meta.url);
const repoRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
const releasePattern = /^build\(tube-vault\): v(\d+\.\d+\.\d+)$/;
const versionPattern = /^\d+\.\d+\.\d+$/;
const ignoredSubjects = new Set(['docs(tube-vault): regenerate changelog']);

const categoryByType = new Map([
  ['feat', 'Added'],
  ['fix', 'Fixed'],
  ['docs', 'Documentation'],
  ['test', 'Tests'],
  ['refactor', 'Maintenance'],
  ['build', 'Maintenance'],
  ['chore', 'Maintenance'],
  ['lint', 'Maintenance'],
]);

const categoryOrder = ['Added', 'Fixed', 'Changed', 'Documentation', 'Tests', 'Maintenance'];

export function parseGitLog(output) {
  return output.trim().split('\n').filter(Boolean).map((line) => {
    const firstTab = line.indexOf('\t');
    const secondTab = line.indexOf('\t', firstTab + 1);
    if (firstTab < 1 || secondTab < 0) throw new Error(`Could not parse Git log record: ${line}`);
    return {
      hash: line.slice(0, firstTab),
      date: line.slice(firstTab + 1, secondTab),
      subject: line.slice(secondTab + 1),
    };
  });
}

function cleanSubject(subject) {
  const conventional = /^(\w+)(?:\([^)]*\))?!?:\s*(.+)$/.exec(subject);
  const type = conventional?.[1]?.toLowerCase();
  let text = conventional?.[2] ?? subject;
  text = text.replaceAll('—', '-').replaceAll('–', '-').trim();
  text = text.charAt(0).toUpperCase() + text.slice(1);
  if (!/[.!?]$/.test(text)) text += '.';
  return { category: categoryByType.get(type) ?? 'Changed', text };
}

export function collectReleases(commits, nextVersion) {
  if (nextVersion && !versionPattern.test(nextVersion)) {
    throw new Error(`Expected --version X.Y.Z, received ${nextVersion}`);
  }

  const releases = [];
  let pending = [];
  for (const commit of commits) {
    if (ignoredSubjects.has(commit.subject)) continue;
    const release = releasePattern.exec(commit.subject);
    if (!release) {
      pending.push(commit);
      continue;
    }
    if (pending.length > 0) releases.push({ version: release[1], commits: pending });
    pending = [];
  }

  if (nextVersion) {
    if (commits.some((commit) => releasePattern.exec(commit.subject)?.[1] === nextVersion)) {
      throw new Error(`Version v${nextVersion} already has a release commit`);
    }
    if (pending.length === 0) throw new Error(`No changes exist for v${nextVersion}`);
    releases.push({ version: nextVersion, commits: pending });
  } else if (pending.length > 0) {
    releases.push({ version: null, commits: pending });
  }

  return releases.reverse();
}

export function renderChangelog(releases) {
  const lines = [
    '# Changelog',
    '',
    '<!-- Generated by `npm run changelog`. Do not edit manually. -->',
    '',
  ];

  for (const release of releases) {
    lines.push(release.version ? `## v${release.version}` : '## Unreleased', '');
    const grouped = new Map(categoryOrder.map((category) => [category, []]));
    for (const commit of release.commits) {
      const entry = cleanSubject(commit.subject);
      grouped.get(entry.category).push(entry.text);
    }
    for (const category of categoryOrder) {
      const entries = grouped.get(category);
      if (entries.length === 0) continue;
      lines.push(`### ${category}`, '');
      for (const entry of entries) lines.push(`- ${entry}`);
      lines.push('');
    }
  }

  return `${lines.join('\n').trimEnd()}\n`;
}

function readHistory(root) {
  const result = spawnSync('git', ['log', '--reverse', '--format=%H%x09%cs%x09%s'], {
    cwd: root,
    encoding: 'utf8',
  });
  if (result.status !== 0) throw new Error(result.stderr.trim() || 'Could not read Git history');
  return parseGitLog(result.stdout);
}

export async function generateChangelog({ root = repoRoot, nextVersion, check = false } = {}) {
  const output = renderChangelog(collectReleases(readHistory(root), nextVersion));
  const changelogPath = resolve(root, 'CHANGELOG.md');
  if (check) {
    const existing = await readFile(changelogPath, 'utf8');
    if (existing !== output) throw new Error('CHANGELOG.md is stale. Run `npm run changelog`.');
    return;
  }
  await writeFile(changelogPath, output);
}

function parseArguments(args) {
  let nextVersion;
  let check = false;
  for (let index = 0; index < args.length; index += 1) {
    if (args[index] === '--check') check = true;
    else if (args[index] === '--version') nextVersion = args[++index];
    else throw new Error(`Unknown argument: ${args[index]}`);
  }
  if (nextVersion === undefined && args.includes('--version')) throw new Error('--version requires a value');
  return { nextVersion, check };
}

export async function main(args = process.argv.slice(2)) {
  await generateChangelog(parseArguments(args));
}

if (process.argv[1] && resolve(process.argv[1]) === scriptPath) {
  await main();
}
